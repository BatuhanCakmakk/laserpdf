const isLang = (s: string | null): s is Lang => !!s && s in dicts;

function initialLang(): Lang {
  try {
    const saved = localStorage.getItem("laserpdf.lang");
    if (isLang(saved)) return saved;
  } catch {
    /* ignore */
  }
  // First run: the first supported system language, otherwise English.
  for (const tag of navigator.languages ?? [navigator.language]) {
    const base = tag.toLowerCase().split("-")[0];
    if (isLang(base)) return base;
  }
  return "en";
}

export let lang: Lang = initialLang();

/** BCP 47 locale of the current language, e.g. for date formatting. */
export function locale(): string {
  return LANGS.find((l) => l.code === lang)!.locale;
}

export function setLang(l: Lang): void {
  lang = l;
  try {
    localStorage.setItem("laserpdf.lang", l);
  } catch {
    /* ignore */
  }
  document.documentElement.lang = locale();
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
